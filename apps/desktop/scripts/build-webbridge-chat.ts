// Bundle what Evo Webbridge's side panel shares with the desktop's thread
// (src/lib/webbridge-chat.ts) into the extension, which has no build step of
// its own:
//
//   bun scripts/build-webbridge-chat.ts           # write sidepanel/vendor/chat.js
//   bun scripts/build-webbridge-chat.ts --check   # fail when it is out of date
import path from "node:path";

const desktop = path.resolve(import.meta.dir, "..");
const entry = path.join(desktop, "src/lib/webbridge-chat.ts");
const out = path.resolve(desktop, "../../extensions/evo-webbridge/sidepanel/vendor/chat.js");

const HEADER = `// Generated by apps/desktop/scripts/build-webbridge-chat.ts from
// apps/desktop/src/lib/webbridge-chat.ts — do not edit. Run
// \`bun run webbridge:chat\` in apps/desktop after changing the sources.
`;

const result = await Bun.build({
  entrypoints: [entry],
  target: "browser",
  format: "esm",
  minify: false,
  tsconfig: path.join(desktop, "tsconfig.json"),
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
// Line endings as written on any system, so the check compares content only.
const code = HEADER + (await result.outputs[0].text()).replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  const current = await Bun.file(out)
    .text()
    .catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== code) {
    console.error(`${path.relative(process.cwd(), out)} is out of date: run \`bun run webbridge:chat\` in apps/desktop.`);
    process.exit(1);
  }
  console.log("side panel chat bundle is up to date");
} else {
  await Bun.write(out, code);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${code.length} bytes)`);
}
